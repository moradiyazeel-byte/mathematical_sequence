    p_clean = (pattern_type or "").lower().strip()
    
    if p_clean in ("powers_of_2", "power") and len(terms) >= 2:
        if all(abs(terms[i+1] / terms[i] - 2.0) < 1e-4 for i in range(len(terms)-1) if terms[i] != 0):
            p_clean = "powers_of_2"

    info = _ALIAS_REGISTRY.get(p_clean)

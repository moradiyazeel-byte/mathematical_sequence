def _format_num(val: float) -> str:
    """Format floating point number to integer if whole, else clean float."""
    if isinstance(val, (int, float)):
        if abs(val - round(val)) < 1e-9:
            return str(int(round(val)))
        return f"{val:.4f}".rstrip("0").rstrip(".")
    return str(val)


def _compute_differences(terms: List[float]) -> List[List[float]]:
    """Compute difference table up to order 3 or until single element."""
    table = []
    curr = list(terms)
    for _ in range(3):
        if len(curr) <= 1:
            break
        diff = [round(curr[i + 1] - curr[i], 6) for i in range(len(curr) - 1)]
        table.append(diff)
        curr = diff
    return table


def _compute_ratios(terms: List[float]) -> List[float]:
    """Compute consecutive ratios."""
    ratios = []
    for i in range(len(terms) - 1):
        if abs(terms[i]) > 1e-9:
            ratios.append(round(terms[i + 1] / terms[i], 4))
        else:
            ratios.append(0.0)
    return ratios


